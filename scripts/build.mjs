import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../', import.meta.url))
const bundle = await build({
  absWorkingDir: root, entryPoints: ['src/client.jsx'], outfile: 'build/client.js',
  bundle: true, format: 'cjs', platform: 'browser', target: 'es2022', jsx: 'automatic',
  external: ['react', 'react/jsx-runtime', '@deepseek-ai/dsh-client-ui-primitives'],
  loader: { '.module.css': 'local-css' }, write: false, legalComments: 'none', charset: 'utf8',
})
const js = bundle.outputFiles.find(file => file.path.endsWith('.js')).text
const css = bundle.outputFiles.find(file => file.path.endsWith('.css')).text
const client = `// Generated by npm run build. Source files live in src/.
window.__ModuleLoader__.load({
  id: 'dsh-project-bookshelf',
  meta() { return {} },
  factory(require) {
    const module = { exports: {} };
    const BOOKSHELF_STYLES = ${JSON.stringify(css)};
    ${js}
    return module.exports;
  }
});
`
await writeFile(new URL('../client.js', import.meta.url), client)
